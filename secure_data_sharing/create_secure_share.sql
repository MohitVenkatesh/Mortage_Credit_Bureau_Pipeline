-- Execute as an appropriately privileged role; replace consumer account details.
CREATE OR REPLACE SECURE VIEW MORTGAGE_DB.GOLD.AUDITOR_DECISIONS_V AS
SELECT APPLICATION_ID, LTV_PCT, DTI_PCT, FICO_SCORE, DECISION, REASON_CODE, DECIDED_AT
FROM MORTGAGE_DB.GOLD.UNDERWRITING_DECISIONS;
-- Create and configure a share only after security/compliance approval.
CREATE SHARE IF NOT EXISTS MORTGAGE_AUDITOR_SHARE;
GRANT USAGE ON DATABASE MORTGAGE_DB TO SHARE MORTGAGE_AUDITOR_SHARE;
GRANT USAGE ON SCHEMA MORTGAGE_DB.GOLD TO SHARE MORTGAGE_AUDITOR_SHARE;
GRANT SELECT ON VIEW MORTGAGE_DB.GOLD.AUDITOR_DECISIONS_V TO SHARE MORTGAGE_AUDITOR_SHARE;
